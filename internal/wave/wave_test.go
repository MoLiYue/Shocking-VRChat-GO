// Every bundled .pulse must convert to exactly the ops stored in its JSON
// preset (which were generated by the Python batch converter).
func TestConvertPulseMatchesBundledPresets(t *testing.T) {
	files, _ := filepath.Glob(filepath.Join(repoRoot, "dg-lab", "*.pulse"))
	if len(files) == 0 {
		t.Skip("no pulse files")
	}
	for _, f := range files {
		stem := strings.TrimSuffix(filepath.Base(f), ".pulse")
		jb, err := os.ReadFile(filepath.Join(repoRoot, "wave_presets", stem+".json"))
		if err != nil {
			continue
		}
		var raw map[string]any
		if err := json.Unmarshal(jb, &raw); err != nil {
			t.Fatal(err)
		}
		want, err := BuildPreset(raw, stem)
		if err != nil {
			t.Fatal(err)
		}
		pb, _ := os.ReadFile(f)
		ops, _, _, secs, err := ConvertPulse(string(pb), 86)
		if err != nil {
			t.Fatalf("%s: %v", stem, err)
		}
		if strings.Join(ops, ",") != strings.Join(want.Ops, ",") {
			t.Errorf("%s: ops mismatch (got %d, want %d)", stem, len(ops), len(want.Ops))
		}
		// preview sections should match as JSON
		gotPS, _ := json.Marshal(PreviewSections(secs))
		wantPS, _ := json.Marshal(raw["preview_sections"])
		var a, b any
		_ = json.Unmarshal(gotPS, &a)
		_ = json.Unmarshal(wantPS, &b)
		ga, _ := json.Marshal(a)
		gb, _ := json.Marshal(b)
		if raw["preview_sections"] != nil && string(ga) != string(gb) {
			t.Errorf("%s: preview_sections mismatch", stem)
		}
	}
}

func TestLibraryWindowsMatchPython(t *testing.T) {
	lib := NewLibrary(filepath.Join(repoRoot, "wave_presets"))
	if len(lib.Names()) < 10 {
		t.Fatalf("expected presets, got %d", len(lib.Names()))
	}
	got := lib.BuildResampledWindow("pulse-舞-1453787", 3.5, 4, 0.7, 0.2, 1.5)
	if want := `["28282828161A1A23","2828282823232D2D","2828282828232319","2828282819192424"]`; got != want {
		t.Errorf("resampled = %s\nwant       %s", got, want)
	}
	got = lib.BuildScaledWindow("soft_rub", 7, 5, 0.33)
	if want := `["F0F0F0F013000010","F0F0F0F021170D17","F0F0F0F021130613","F0F0F0F021181018","F0F0F0F021140814"]`; got != want {
		t.Errorf("scaled = %s\nwant    %s", got, want)
	}
	if lib.Get("does-not-exist") != nil {
		t.Error("expected nil for missing preset")
	}
}

